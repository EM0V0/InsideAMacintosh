export const FONT = { ascent: 9, descent: 2, lineHeight: 12, glyphs: {} };
for (const [ch, rows] of Object.entries(G)) {
  const w = rows.reduce((m, r) => Math.max(m, r.length), 0);
  const bits = rows.map((r) => { let v = 0; for (let i = 0; i < r.length; i++) if (r[i] === '#') v |= 1 << (w - 1 - i); return v; });
  FONT.glyphs[ch] = { w, bits };
}
FONT.glyphs[' '] = { w: 3, bits: [] };
FONT.glyphs['\t'] = { w: 12, bits: [] };
const MISSING = FONT.glyphs['?'];

export function glyph(ch) { return FONT.glyphs[ch] || MISSING; }
export function charWidth(ch, bold = false) { const g = glyph(ch); return g.w + 1 + (bold && g.bits.length ? 1 : 0); }
export function textWidth(str, bold = false) {
  let w = 0;
  for (const ch of str) w += charWidth(ch, bold);
  return Math.max(0, w - 1);
}

// word wrap: returns lines as {s, e} index ranges into text (newlines excluded)
export function wrapText(text, width, bold = false) {
  const lines = [];
  const n = text.length;
  let i = 0;
  for (;;) {
    let pe = text.indexOf('\n', i); if (pe < 0) pe = n;
    if (pe === i) lines.push({ s: i, e: i });
    let s = i;
    while (s < pe) {
      let w = 0, e = s, brk = -1;
      while (e < pe) {
        const cw = charWidth(text[e], bold);
        if (w + cw - 1 > width && e > s) break;
        w += cw; if (text[e] === ' ') brk = e; e++;
      }
      if (e < pe && brk >= s) e = brk + 1;
      lines.push({ s, e });
      s = e;
    }
    if (pe >= n) break;
    i = pe + 1;
    if (i === n) { lines.push({ s: n, e: n }); break; }
  }
  if (!lines.length) lines.push({ s: 0, e: 0 });
  return lines;
}
